// סימולציה: שיחות נפרדות בדף Claude באתר הצאט (conv), כולל הקשר לריצה
import { CallState } from "../entry.js";
const data = new Map();
const storage = { get: async (k) => data.get(k), put: async (k, v) => { data.set(k, JSON.parse(JSON.stringify(v))); }, delete: async (k) => data.delete(k) };
const env = {};
const doObj = new CallState({ storage }, env);
const call = async (op, body) => (await doObj.fetch(new Request("https://do/bridge/" + op, { method: "POST", body: JSON.stringify(body || {}) }))).json();
const ok = (c, m) => { if (!c) { console.error("FAIL:", m); process.exit(1); } };
const a1 = await call("siteadd", { text: "שלום", conv: "c1" });
let t = await call("take");
ok(t.messages[0].text === "שלום", "first message plain");
await call("answer", { re: a1.id, text: "שלום לך" });
await call("siteadd", { text: "עוד שאלה", conv: "c1" });
await call("siteadd", { text: "נושא אחר", conv: "c2" });
t = await call("take");
ok(t.messages[0].text.startsWith("עוד שאלה") && t.messages[0].text.includes("Claude: שלום לך"), "context added in same conv");
ok(t.messages[1].text === "נושא אחר", "no context from other conv");
const h = await call("site");
ok(h.items.length === 4, "history count");
ok(h.items.find((x) => x.from === "claude").conv === "c1", "answer inherits conv");
ok(h.items.find((x) => x.text === "עוד שאלה"), "history shows plain text");
ok(h.items.filter((x) => x.conv === "c2").length === 1, "conv c2");
console.log("site conversations: passed");
const big = "קובץ: " + "א".repeat(9000);
const b1 = await call("siteadd", { text: big, conv: "c3" });
t = await call("take");
ok(t.messages[0].text.length === big.length, "full attachment reaches the run");
ok(!data.has("sb:" + b1.id), "full text removed after take");
ok((await call("site")).items.find((x) => x.id === b1.id).text.length === 1200, "history keeps 1200");
console.log("attachments: passed");
